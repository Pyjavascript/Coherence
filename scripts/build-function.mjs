// Bundles the generate Edge Function into one self-contained index.ts.
//
// The function's code lives in supabase/functions/generate/handler.ts and
// imports the prompt builders from supabase/functions/_shared (shared with the
// web app). Supabase only bundles what it's given: the dashboard editor and
// some CLI setups upload index.ts alone, so ../_shared isn't found. Bundling
// it all into index.ts works with every way of deploying.
//
// Run after changing handler.ts or anything in _shared:  npm run build:function
import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "supabase/functions/generate");

await build({
  entryPoints: [path.join(dir, "handler.ts")],
  outfile: path.join(dir, "index.ts"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  // Deno resolves npm: imports itself at deploy time.
  external: ["npm:*"],
  legalComments: "none",
  logLevel: "warning",
  banner: {
    js: [
      "// @ts-nocheck",
      "// GENERATED by `npm run build:function` from handler.ts and ../_shared/*.js.",
      "// Don't edit this file: edit those, then rebuild. Deploy this file as is",
      "// (supabase functions deploy generate, or paste it into the dashboard editor).",
      "",
    ].join("\n"),
  },
});

console.log("Built supabase/functions/generate/index.ts");
